//! BurpFree out-of-band (OOB) interaction engine.
//!
//! Think of this as the Collaborator-style companion the active scanner
//! and Intruder use to detect vulnerabilities whose only observable
//! signal is an outbound interaction (SSRF, blind command injection,
//! Log4Shell, blind SQLi via DNS exfil, insecure deserialization that
//! fires a webhook, …).
//!
//! Architecture:
//!
//! * [`OobServer`] binds an HTTP listener (default `127.0.0.1:7898`)
//!   and optionally a UDP DNS listener (admin on Windows for :53;
//!   default is a high port like `15353`).
//! * [`OobServer::new_token`] mints a unique correlation id and returns
//!   an [`OobToken`] carrying a prebuilt HTTP URL and DNS hostname that
//!   can be injected into a payload.
//! * Every incoming HTTP or DNS probe that mentions the correlation id
//!   is appended to the interaction log.
//! * [`OobServer::drain_since`] / [`poll_for`] let the scanner/intruder
//!   correlate an attack with a callback within a timeout window.
//!
//! The server is per-project: tokens generated by one project never
//! correlate with another even if the listener is shared, because the
//! correlation id namespace is scoped by the server instance.

pub mod payload;
pub mod server;

pub use payload::{build_payloads_for, PayloadFamily};
pub use server::{
    Interaction, InteractionKind, OobConfig, OobServer, OobServerHandle, OobToken,
};
