/// Generate a clickjacking PoC from URL + overlay label.
/// Legacy wrapper matching the pre-R938 `generate_clickjacking_html` signature.
pub fn generate_clickjacking_html(url: &str, _overlay_label: &str) -> String {
    clickjacking_poc(url, 800, 600)
}

/// Generate a CSRF PoC from a parsed Request.
/// Legacy wrapper matching the pre-R938 `generate_csrf_html` signature.
pub fn generate_csrf_html(req: &burpfree_core::traffic::Request) -> String {
    let url = format!(
        "{}://{}{}",
        req.scheme,
        req.host,
        req.path,
    );
    // Extract form parameters from the body if present
    let params: Vec<(&str, &str)> = Vec::new(); // TODO: parse req.body as form params
    csrf_poc(&url, &req.method, &params)
}
