//! Scanner Knowledge Base — issue type descriptions matching Burp Suite's
//! `resources/KnowledgeBase/Issues/*`. Every finding references a KB entry
//! so operators get a standardized description, remediation, and CWE/OWASP
//! mapping regardless of which detector produced the finding.

use serde::Serialize;

/// A knowledge base issue entry.
#[derive(Debug, Clone, Serialize)]
pub struct KbIssue {
    pub id: &'static str,
    pub name: &'static str,
    pub description: &'static str,
    pub remediation: &'static str,
    pub severity_default: &'static str,
    pub cwe: &'static [&'static str],
    pub owasp: &'static [&'static str],
    pub references: &'static [&'static str],
}

/// Return all knowledge base issues.
pub fn knowledge_base() -> &'static [KbIssue] {
    ISSUES
}

/// Look up a KB issue by id.
pub fn lookup(id: &str) -> Option<&'static KbIssue> {
    ISSUES.iter().find(|i| i.id == id)
}

